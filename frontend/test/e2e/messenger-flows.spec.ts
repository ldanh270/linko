import { expect, test } from "@playwright/test"
import { FIXTURE_IDS, installMessengerFixtures } from "./fixtures/messenger"
import { HTTP_ERROR } from "../../shared/http/ApiError"

test("should_keep_theme_and_logout_available_when_profile_loading_fails", async ({ page }) => {
  await installMessengerFixtures(page, { failProfile: true })
  await page.goto("/settings")
  await expect(page.getByRole("heading", { name: "Không thể tải tài khoản", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "Đăng xuất khỏi thiết bị", exact: true })).toBeVisible()
  await expect(page.getByRole("radio", { name: "Tối", exact: true })).toBeVisible()
  await page.getByRole("radio", { name: "Tối", exact: true }).check()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
})

test("should_not_mark_a_hidden_mobile_conversation_as_read", async ({ page }) => {
  const fixture = await installMessengerFixtures(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/profile?conversation=${FIXTURE_IDS.DIRECT}`)
  await expect(page.getByRole("heading", { name: "Hồ sơ của tôi", exact: true })).toBeVisible()
  await expect(page.getByRole("textbox", { name: "Soạn tin nhắn", exact: true })).toHaveCount(0)
  await expect(page.getByRole("log")).toHaveCount(0)
  expect(fixture.readRequests).toHaveLength(0)
  await page.goto(`/direct/${FIXTURE_IDS.DIRECT}`)
  await expect.poll(() => fixture.readRequests.length).toBeGreaterThan(0)
})

test("should_retry_failed_send_with_the_same_identity_and_reset_draft_on_recipient_change", async ({ page }) => {
  const fixture = await installMessengerFixtures(page, { failFirstSend: true })
  await page.goto(`/direct/${FIXTURE_IDS.DIRECT}`)
  const input = page.getByRole("textbox", { name: "Soạn tin nhắn", exact: true })
  await input.fill("Một tin nhắn thử")
  await page.getByRole("button", { name: "Gửi tin nhắn", exact: true }).click()
  await expect(page.getByRole("alert").filter({ hasText: HTTP_ERROR.GENERIC_MESSAGE })).toBeVisible()
  expect(fixture.requests).toHaveLength(1)
  await page.getByRole("button", { name: "Gửi tin nhắn", exact: true }).click()
  await expect(page.locator('article[data-owner="self"]').getByText("Một tin nhắn thử", { exact: true })).toBeVisible()
  expect(fixture.requests).toHaveLength(2)
  expect(fixture.requests[0].clientMessageId).toBe(fixture.requests[1].clientMessageId)
  await input.fill("Bản nháp cho Doris")
  await page.getByRole("listitem").filter({ hasText: "General" }).getByRole("link").click()
  await expect(page).toHaveURL(`/groups/${FIXTURE_IDS.GROUP}`)
  await expect(page.getByRole("textbox", { name: "Soạn tin nhắn", exact: true })).toHaveValue("")
})

test("should_search_contacts_open_a_direct_chat_and_keep_mobile_back_navigation", async ({ page }) => {
  await installMessengerFixtures(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/people")
  await page.getByRole("searchbox", { name: "Tìm trong danh bạ" }).pressSequentially("Doris", { delay: 40 })
  await expect(page).toHaveURL(/q=Doris/)
  await page.getByRole("article").filter({ has: page.getByText("Doris Brown", { exact: true }) }).getByRole("button", { name: "Nhắn tin", exact: true }).click()
  await expect(page).toHaveURL(`/direct/${FIXTURE_IDS.DIRECT}`)
  await expect(page.getByRole("region", { name: "Cuộc trò chuyện", exact: true })).toBeVisible()
  await page.getByRole("link", { name: "Về danh sách tin nhắn" }).click()
  await expect(page.getByRole("heading", { name: "Tin nhắn", exact: true })).toBeVisible()
})

test("should_edit_profile_share_updated_identity_and_confirm_logout", async ({ page }) => {
  await installMessengerFixtures(page)
  await page.goto(`/profile?conversation=${FIXTURE_IDS.DIRECT}`)
  await page.getByRole("button", { name: "Chỉnh sửa hồ sơ", exact: true }).click()
  await page.getByRole("textbox", { name: "Tên hiển thị" }).fill("Nguyễn An")
  await page.getByRole("button", { name: "Lưu thay đổi hồ sơ", exact: true }).click()
  await expect(page.getByRole("status").filter({ hasText: "Đã lưu thay đổi hồ sơ thành công." })).toBeVisible()
  await page.getByRole("button", { name: "Đóng", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Nguyễn An", exact: true })).toBeVisible()
  await page.getByRole("navigation", { name: "Chính", exact: true }).getByRole("link", { name: "Cài đặt" }).click()
  await page.getByRole("radio", { name: "Tối", exact: true }).check()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
  await page.getByRole("button", { name: "Đăng xuất khỏi thiết bị", exact: true }).click()
  await expect(page.getByRole("dialog", { name: "Đăng xuất khỏi Linko?" })).toBeVisible()
  await page.getByRole("button", { name: "Ở lại" }).click()
  await expect(page.getByRole("dialog")).not.toBeVisible()
  await page.getByRole("button", { name: "Đăng xuất khỏi thiết bị", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Đăng xuất", exact: true }).click()
  await expect(page).toHaveURL("/login")
  await expect(page.getByRole("log", { name: "Tin nhắn", exact: true })).toHaveCount(0)
})
